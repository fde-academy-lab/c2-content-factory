import sys, pandas as pd, numpy as np
t = pd.read_csv(sys.argv[1])
print('TELCO', t.shape)
y = (t.Churn=='Yes').astype(int); print('churn base', y.mean().round(4), y.sum())
print('TotalCharges dtype', t.TotalCharges.dtype, 'blank', (t.TotalCharges.str.strip()=='').sum())
print('tenure of blanks', t.loc[t.TotalCharges.str.strip()=='', 'tenure'].unique(), 'tenure==0', (t.tenure==0).sum())
print('dup customerID', t.customerID.duplicated().sum(), 'dup rows excl id', t.drop(columns='customerID').duplicated().sum())
tc = pd.to_numeric(t.TotalCharges, errors='coerce')
print('TotalCharges vs tenure*Monthly corr', np.corrcoef(tc.fillna(0), t.tenure*t.MonthlyCharges)[0,1].round(4))
print('churn by contract', t.groupby('Contract').Churn.apply(lambda s:(s=="Yes").mean()).round(3).to_dict())
print('gender', t.gender.value_counts().to_dict(), 'Senior', t.SeniorCitizen.value_counts().to_dict())
h = pd.read_csv(sys.argv[2])
print('HILLSTROM', h.shape, list(h.columns))
print('missing', int(h.isna().sum().sum()), 'dups', h.duplicated().sum())
g = h.groupby('segment').agg(n=('visit','size'), visit=('visit','mean'), conv=('conversion','mean'), spend=('spend','mean')).round(5)
print(g)
print('zip', h.zip_code.value_counts().to_dict(), 'channel', h.channel.value_counts().to_dict())
print('history_segment', h.history_segment.value_counts().sort_index().to_dict())
print('recency range', h.recency.min(), h.recency.max())
print('spend>0', (h.spend>0).sum(), 'conversion==1', h.conversion.sum(), 'spend>0 but conv0', ((h.spend>0)&(h.conversion==0)).sum())

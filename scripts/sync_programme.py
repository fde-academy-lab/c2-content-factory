def load_facts():
    facts = yaml.safe_load(FACTS.read_text(encoding="utf-8"))
    for key in ("calendar", "faculty", "evaluation", "modules", "decisions", "conflicts"):
        if key not in facts:
            sys.exit(f"FAIL  {FACTS} has no '{key}' section")
    return facts


def read_tracker_days(wb, facts, report):
    """Every day row of every day tab, as dicts, plus the capstone weeks as week-level records."""
    holidays = {as_date(h["date"]): h["name"] for h in facts["calendar"]["holidays"]}
    modules = facts["modules"]["weeks"]
    exceptions = facts["modules"].get("day_exceptions") or {}
    days, weeks = [], {}
    for ws in wb.worksheets:
        shape = ec.shape_of(ws)
        if shape not in ("days", "weekly"):
            continue
        n = int(re.match(r"^W(\d+)", ws.title).group(1))
        if shape == "weekly":
            continue
        headers = ec.headers_of(ws)
        col = {h: i + 1 for i, h in enumerate(headers) if h}
        kind_of_week = ("baseline" if n == 0 else
                        "build-week" if re.search(r"\bBuild\b", ws.title) else "teaching")
        for r in range(ec.FIRST_DATA_ROW, ws.max_row + 1):
            raw = ec.clean(ws.cell(row=r, column=col["Day"]).value)
            if not raw:
                continue
            parts = raw.split("\n")
            date = dt.datetime.strptime(parts[-1].strip(), "%d %b %Y").date()
            if date.strftime("%a") != parts[0].strip()[:3]:
                report.error(f"{ws.title}: '{raw}' names the wrong weekday for its date")
            focus_cell = ec.clean(ws.cell(row=r, column=col["Day focus"]).value)
            topic, _, focus = focus_cell.partition(" · ")
            if not focus:
                topic, focus = "", topic
            wd = date.weekday()
            says_off = bool(re.search(r"no session", focus_cell, re.I))
            if date in holidays and not says_off:
                report.error(f"{ws.title}: {long_date(date)} is {holidays[date]} in facts.yaml, "
                             f"but the tracker row teaches")
            if says_off and date not in holidays:
                report.error(f"{ws.title}: {long_date(date)} says no session, but facts.yaml has no "
                             f"holiday on that date")
            if date in holidays:
                kind, slot = "holiday", HOLIDAY_SLOT[wd]
            elif wd == 5:
                slot = "SAT"
                kind = ("saturday" if kind_of_week == "teaching" and topic.lower().startswith("saturday")
                        else kind_of_week)
            else:
                kind, slot = kind_of_week, f"D{wd + 1}"
            violet = ec.clean(ws.cell(row=r, column=col[VIOLET]).value) if VIOLET in col else ""
            key = f"{week_key(n)}/{slot}"
            days.append({
                "week": week_key(n), "slot": slot, "date": date, "weekday": WEEKDAYS[wd],
                "kind": kind, "topic": topic.strip(), "focus": focus.strip(),
                "module": exceptions.get(key, modules.get(week_key(n))),
                "holiday": holidays.get(date), "violet": violet,
                "violet_ids": SESSION_ID.findall(violet), "tab": ws.title,
            })
        weeks[week_key(n)] = {"number": n, "kind": kind_of_week, "tab": ws.title}
    return days, weeks


def read_capstone(wb, facts):
    """The capstone tab's week rows: 'Wk 17\\n25 to 30 Jan 2027\\nFrame, propose, ...'."""
    out = {}
    monday1 = as_date(facts["calendar"]["week1_monday"])
    for ws in wb.worksheets:
        if ec.shape_of(ws) != "weekly":
            continue
        for r in range(ec.FIRST_DATA_ROW, ws.max_row + 1):
            cell = ec.clean(ws.cell(row=r, column=1).value)
            m = re.match(r"^Wk (\d+)\n", cell)
            if not m or "Sat" in cell.split("\n")[0]:
                continue
            n = int(m.group(1))
            lines = [p.strip() for p in cell.split("\n") if p.strip()]
            monday = monday1 + dt.timedelta(weeks=n - 1)
            out[week_key(n)] = {"number": n, "kind": "capstone", "tab": ws.title,
                                "monday": monday, "focus": lines[-1]}
    return out


def read_plan(wb):
    """The 20-Week Plan's grid, keyed W00 to W20."""
    ws = wb[ec.PLAN_TAB]
    header_row = next(r for r in range(1, ws.max_row + 1)
                      if ec.clean(ws.cell(row=r, column=1).value) == ec.PLAN_FIRST_HEADER)
    headers = ec.headers_of(ws, header_row)
    out = {}
    for r in range(header_row + 1, ws.max_row + 1):
        first = ec.clean(ws.cell(row=r, column=1).value)
        if not re.fullmatch(r"\d+", first):
            break
        row = {headers[c - 1]: ec.clean(ws.cell(row=r, column=c).value)
               for c in range(1, len(headers) + 1) if headers[c - 1]}
        out[week_key(int(first))] = row
    return out


def parse_span(text, year_hint):
    """'05 to 10 Oct 2026', '28 Sep to 03 Oct 2026' or '28 Dec 2026 to 02 Jan 2027' as two dates."""
    first = text.split("\n")[0].strip()
    m = re.match(r"^(\d{1,2})(?: ([A-Z][a-z]{2}))?(?: (\d{4}))? to (\d{1,2}) ([A-Z][a-z]{2}) (\d{4})$", first)
    if not m:
        return None, None
    d1, mon1, y1, d2, mon2, y2 = m.groups()
    end = dt.datetime.strptime(f"{d2} {mon2} {y2}", "%d %b %Y").date()
    start = dt.datetime.strptime(f"{d1} {mon1 or mon2} {y1 or y2}", "%d %b %Y").date()
    return start, end


def read_faculty(path, facts, report):
    """The Sessions tab, one dict per session, with facts.yaml overrides laid on top."""
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb["Sessions"]
    header_row = next(r for r in range(1, ws.max_row + 1)
                      if ec.clean(ws.cell(row=r, column=1).value) == "Session")
    headers = ec.headers_of(ws, header_row)
    col = {h: i + 1 for i, h in enumerate(headers) if h}
    sessions, banner, progress = [], "", ""
    publish = bool(facts["faculty"].get("publish_names"))
    for r in range(header_row + 1, ws.max_row + 1):
        first = ec.clean(ws.cell(row=r, column=1).value)
        if first.startswith("WEEK "):
            banner = first
            continue
        if first.startswith("Learner progress"):
            progress = first
            continue
        if not re.fullmatch(r"W\d+-\d+", first):
            continue
        get = lambda name: ec.clean(ws.cell(row=r, column=col[name]).value) if name in col else ""
        s = {
            "id": first, "week": week_key(int(get("Week") or 0)),
            "date": as_date(ws.cell(row=r, column=col["Date"]).value),
            "minutes": int(float(get("Duration (min)") or 0)),
            "module_subject": get("Module and subject"), "topic": get("Session topic"),
            "subtopics": get("Subtopics"), "outcomes": get("Learning outcomes"),
            "place": get("Place in the programme"), "prior": get("Prior coverage"),
            "reserved": get("Reserved for later sessions"), "references": get("Suggested references"),
            "faculty": get("Faculty member"), "status": get("Status") or "Tentative",
            "remarks": get("Remarks"), "banner": banner, "progress": progress, "row": r,
            "overridden": False,
        }
        if s["faculty"].lower() not in NO_NAME and not publish:
            report.error(f"{path} row {r} names a faculty member for {s['id']}, and facts.yaml says "
                         f"faculty.publish_names is false. The repository is public: clear that "
                         f"column before committing the workbook, or make the repository private "
                         f"and set publish_names to true.")
        sessions.append(s)
    for sid, change in (facts["faculty"].get("overrides") or {}).items():
        hit = next((s for s in sessions if s["id"] == sid), None)
        if not hit:
            report.error(f"facts.yaml faculty.overrides names {sid}, which the workbook does not have")
            continue
        for k, v in change.items():
            hit[k] = as_date(v) if k == "date" else v
        hit["overridden"] = True
        if (hit.get("faculty") or "").lower() not in NO_NAME and not publish:
            report.error(f"facts.yaml overrides {sid} with a faculty name while publish_names is false")
    overview = {}
    ov = wb["Overview"]
    for r in range(1, ov.max_row + 1):
        if ec.clean(ov.cell(row=r, column=1).value) == "Input":
            overview[ec.clean(ov.cell(row=r, column=2).value)] = ov.cell(row=r, column=3).value
    return sessions, overview, wb



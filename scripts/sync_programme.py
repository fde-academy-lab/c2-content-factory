"""Regenerate everything that follows from the programme's movable facts, with one command.

    python3 scripts/sync_programme.py           # check the sources, regenerate, say what changed
    python3 scripts/sync_programme.py --check   # write nothing; exit 1 if anything is stale or wrong

Edit the sources, never the outputs:

    docs/curriculum/source.xlsx   the curriculum tracker: every week and day, the Structure tab,
                                  the 20-Week Plan, the capstone plan and the Saturday item bank
    docs/faculty/source.xlsx      the IITGN faculty session plan, tentative until IITGN confirms
    docs/journey/source.xlsx      the student-facing 20-week journey and Week 0 sheet
    data/programme/facts.yaml     every movable fact the workbooks do not hold, each with a status

The sync checks that the sources agree before it writes anything: every holiday in the facts is a
no-session day in the tracker and the other way round, the 20-Week Plan's dates match the day tabs,
every faculty session sits on a teaching day inside its own week, the violet column of the tracker
and the faculty workbook place each session on the same day, the per-week session counts agree,
and no faculty name reaches the repository while facts.yaml says names stay unpublished. Then it
writes:

    docs/curriculum/*.md, docs/faculty/*.md, docs/journey/*.md   the workbook exports
    data/programme/days.json      one record per day, which scripts/board_sync.py reads
    docs/programme/*.md           the calendar, the faculty plan and the decisions register
    content/W{ww}/SAT/paper and answer-key, for every week whose paper is already built,
                                  with data/programme/paper_edits.yaml laid on top
    every <!-- sync:NAME --> ... <!-- /sync:NAME --> block in the markdown under docs/, content/,
    prompts/, wiki/ and .claude/skills/, plus CLAUDE.md, re-rendered for its file's audience
    docs/claude-project/knowledge/  the files the claude.ai Project is loaded with

When IIT Gandhinagar confirms or moves a session, replace docs/faculty/source.xlsx with the returned
workbook (with the Faculty member column cleared while the repository is public), or add one line
under faculty.overrides in facts.yaml, then run the sync. When a holiday, a status or a decision
changes, edit facts.yaml and run the sync. On GitHub, the programme-sync workflow runs the same
command on any branch that changes a source and commits what it regenerates.

The block names a markdown file can carry, and what each renders:

    sync:status                    the one-line state of the movable facts, with its date
    sync:calendar-summary          the week table: dates, kind, module, holidays, faculty sessions
    sync:faculty-summary           the faculty plan by week, with statuses
    sync:evaluation                the evaluation proposals and their status (never in STUDENT files)
    sync:decisions                 the open decisions and the known conflicts (never in STUDENT files)
    sync:module:W02/D1             the module a day posts to, as "Module 1: Foundations of AI and Data"
    sync:day-date:W02/D1           the day's date, as "Mon 12 Oct 2026"
    sync:faculty-day:W02/D1        that day's IITGN block, or a line saying there is none
    sync:rubric:W03                a build's settled rubrics and graded days, from evaluation.rubrics
    sync:rubric:W03/mock           one of them: mini-project, mock or gd

A file's audience comes from its name: _STUDENT, _TRAINER or _INTERNAL, and INTERNAL for anything
else. A STUDENT file never receives a proposed or open fact, and a tentative one arrives with the
word tentative beside it.
"""

def render_status(ctx, arg, audience):
    f = ctx.facts
    confirmed = sum(1 for s in ctx.sessions if ctx.status_word(s) == "confirmed")
    opened = sum(1 for d in f["decisions"] if d.get("status") == "open")
    parts = [f"Facts as of {dt.date.fromisoformat(str(f['as_of'])).strftime('%d %b %Y')}: "
             f"calendar {f['calendar']['status']} on "
             f"{as_date(f['calendar']['locked_on']).strftime('%d %b %Y')}",
             f"IITGN faculty sessions {len(ctx.sessions)} planned, {confirmed} confirmed",
             f"client zero {f['client_zero']['locked']['version']} locked and "
             f"{f['client_zero']['proposed']['version']} {f['client_zero']['proposed']['status']}"]
    if audience != "STUDENT":
        parts += [f"evaluation {f['evaluation']['status']}", f"{opened} decisions open"]
    return "; ".join(parts) + "."


def render_calendar_summary(ctx, arg, audience):
    rows = []
    for wk in sorted(set(ctx.plan) | set(ctx.capstone)):
        n = int(wk[1:])
        mon = week_monday(ctx, wk)
        sat = mon + dt.timedelta(days=5)
        kind = (ctx.capstone[wk]["kind"] if wk in ctx.capstone else ctx.weeks[wk]["kind"])
        offs = [f"{short_date(d['date'])}, {d['holiday']}" for d in ctx.days
                if d["week"] == wk and d["holiday"]]
        offs += [f"{short_date(as_date(h['date']))}, {h['name']}" for h in ctx.facts["calendar"]["holidays"]
                 if wk in ctx.capstone and mon <= as_date(h["date"]) <= sat]
        sess = [s for s in ctx.sessions if s["week"] == wk]
        if sess:
            conf = sum(1 for s in sess if ctx.status_word(s) == "confirmed")
            fac = f"{len(sess)} ({conf} confirmed)" if audience != "STUDENT" or conf else f"{len(sess)}, tentative"
        else:
            fac = "none"
        module = ctx.facts["modules"]["weeks"].get(wk)
        rows.append([str(n), f"{mon.strftime('%d %b')} to {sat.strftime('%d %b %Y')}", kind,
                     module or "none", week_label(ctx, wk), "; ".join(offs) or "none", fac])
    head = ["Week", "Mon to Sat", "Kind", "Module", "Focus", "Holidays", "IITGN sessions"]
    return "\n".join(ec.md_table(head, rows))


def render_faculty_summary(ctx, arg, audience):
    f = ctx.facts["faculty"]
    lines = [f"Status: {f['status']} until {f['confirms']}. {len(ctx.sessions)} sessions of "
             f"{f['session_minutes']} minutes, {sum(s['minutes'] for s in ctx.sessions) / 60:g} hours "
             f"against {f['hours_committed']} committed. {f['placement']}", ""]
    rows = []
    for s in ctx.sessions:
        rows.append([s["id"], short_date(s["date"]), s.get("slot", ""), s["topic"],
                     s["status"] + (" (override)" if s["overridden"] else ""),
                     ctx.faculty_label(s)])
    lines += ec.md_table(["Session", "Date", "Day", "Topic", "Status", "Faculty"], rows)
    if audience != "STUDENT" and f.get("ruling", {}).get("status") == "open":
        lines += ["", f"Open ruling: {f['ruling']['text']}"]
    return "\n".join(lines)


def render_evaluation(ctx, arg, audience):
    if audience == "STUDENT":
        raise ValueError("the evaluation block never renders in a STUDENT file")
    ev = ctx.facts["evaluation"]
    comps = ["major_exams", "mini_projects", "mock_interviews", "business_gds", "capstone"]
    head = ["Version", "Status", "Major exams", "Mini projects", "Mock interviews", "Business GDs",
            "Capstone", "Source"]

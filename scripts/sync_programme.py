def check_calendar(days, plan, capstone, facts, report):
    monday1 = as_date(facts["calendar"]["week1_monday"])
    monday0 = as_date(facts["calendar"]["week0_monday"])
    if monday1 - monday0 != dt.timedelta(weeks=1):
        report.error("facts.yaml: week0_monday is not the Monday before week1_monday")
    by_week = {}
    for d in days:
        by_week.setdefault(d["week"], []).append(d)
    for wk, row in plan.items():
        n = int(wk[1:])
        want_mon = monday0 if n == 0 else monday1 + dt.timedelta(weeks=n - 1)
        start, end = parse_span(row.get("Dates (Mon to Sat)", ""), want_mon.year)
        if start != want_mon or end != want_mon + dt.timedelta(days=5):
            report.error(f"20-Week Plan: week {n} prints '{row.get('Dates (Mon to Sat)', '')}', "
                         f"but the calendar puts it at {short_date(want_mon)} to "
                         f"{long_date(want_mon + dt.timedelta(days=5))}")
        if wk in by_week:
            got = sorted(d["date"] for d in by_week[wk])
            if got[0] != want_mon or got[-1] != want_mon + dt.timedelta(days=5) or len(got) != 6:
                report.error(f"{by_week[wk][0]['tab']}: its days do not run Monday to Saturday of "
                             f"the week the calendar gives it")
        elif wk not in capstone:
            report.error(f"20-Week Plan has week {n}, but the tracker has no tab for it")
    last = as_date(facts["calendar"]["last_day"])
    if plan and max(int(w[1:]) for w in plan) != (last - monday1).days // 7 + 1:
        report.error("facts.yaml last_day does not fall in the plan's last week")
    for h in facts["calendar"]["holidays"]:
        date = as_date(h["date"])
        if not any(d["date"] == date for d in days) and not any(
                c["monday"] <= date <= c["monday"] + dt.timedelta(days=5) for c in capstone.values()):
            report.error(f"facts.yaml holiday {h['name']} on {long_date(date)} falls on no programme day")


def check_faculty(sessions, days, plan, facts, report):
    by_date = {d["date"]: d for d in days}
    per_week, seen = {}, set()
    minutes = facts["faculty"].get("session_minutes", 120)
    for s in sessions:
        if s["id"] in seen:
            report.error(f"faculty workbook: {s['id']} appears twice")
        seen.add(s["id"])
        per_week[s["week"]] = per_week.get(s["week"], 0) + 1
        day = by_date.get(s["date"])
        if not s["date"] or not day:
            report.error(f"{s['id']}: its date {s['date']} is not a programme day")
            continue
        s["slot"] = f"{day['week']}/{day['slot']}"
        if day["week"] != s["week"]:
            report.error(f"{s['id']}: dated {long_date(s['date'])}, which is in {day['week']}, "
                         f"not {s['week']}")
        if day["kind"] != "teaching" or day["weekday"] == "Sat":
            what = {"saturday": "the Saturday recap", "holiday": f"a holiday ({day['holiday']})",
                    "build-week": "a build-week day", "baseline": "in the baseline week"}.get(
                        day["kind"], "a Saturday")
            report.error(f"{s['id']}: {long_date(s['date'])} is {what}, and a faculty block runs "
                         f"on a weekday teaching day only")
        if s["minutes"] != minutes:
            report.warn(f"{s['id']} runs {s['minutes']} minutes against the planned {minutes}")
        if s["id"] not in day["violet_ids"]:
            placed = [d for d in days if s["id"] in d["violet_ids"]]
            where = f"{placed[0]['week']}/{placed[0]['slot']}" if placed else "no day"
            source = "facts.yaml overrides it to" if s["overridden"] else "the faculty workbook puts it on"
            text = (f"{s['id']}: {source} {long_date(s['date'])} ({s['slot']}); the tracker's "
                    f"violet column puts it on {where}.")
            if s["overridden"]:
                report.warn(text + " The override in facts.yaml wins until the tracker catches up.")
            else:
                report.warn(text + " The workbook wins; update the tracker's violet column.")
    ids = {s["id"] for s in sessions}
    for d in days:
        for sid in d["violet_ids"]:
            if sid not in ids:
                report.error(f"{d['tab']}: {short_date(d['date'])} names session {sid}, which the "
                             f"faculty workbook does not have")
    for wk, row in plan.items():
        want = int(float(row.get("IITGN sessions (tentative)") or 0))
        if per_week.get(wk, 0) != want:
            report.error(f"20-Week Plan gives week {int(wk[1:])} {want} IITGN sessions; the faculty "
                         f"workbook has {per_week.get(wk, 0)}")
    total_hours = sum(s["minutes"] for s in sessions) / 60
    if total_hours != facts["faculty"].get("hours_committed"):
        report.warn(f"the faculty sessions add to {total_hours:g} hours against "
                    f"{facts['faculty'].get('hours_committed')} committed")
    doubles = {}
    for s in sessions:
        doubles.setdefault(s["date"], []).append(s["id"])
    for date, sids in doubles.items():
        if len(sids) > 1:
            report.warn(f"{long_date(date)} carries {len(sids)} faculty sessions: {', '.join(sids)}")


# --------------------------------------------------------------------------- the context
class Context:
    def __init__(self, facts, days, weeks, capstone, plan, sessions):
        self.facts, self.days, self.weeks, self.capstone = facts, days, weeks, capstone
        self.plan, self.sessions = plan, sessions
        self.day = {f"{d['week']}/{d['slot']}": d for d in days}
        self.violet_text = {}
        for d in days:
            for sid in d["violet_ids"]:
                self.violet_text[sid] = d["violet"]

    def module_name(self, code):
        if not code:
            return "no module, since Week 0 sits outside the 510 hours"
        n = code[1:]
        return f"Module {n}: {self.facts['modules']['names'][code]}"

    def sessions_on(self, date):
        return [s for s in self.sessions if s["date"] == date]

    def faculty_label(self, s):
        name = (s.get("faculty") or "").strip()
        if name.lower() in NO_NAME:
            return "to be confirmed by IIT Gandhinagar"
        if self.facts["faculty"].get("publish_names"):
            return name
        return "named in the workbook, not published here"

    def status_word(self, s):
        return (s.get("status") or "Tentative").strip().lower()


def week_monday(ctx, wk):
    if wk in ctx.capstone:
        return ctx.capstone[wk]["monday"]
    return min(d["date"] for d in ctx.days if d["week"] == wk)


def week_label(ctx, wk):
    row = ctx.plan.get(wk, {})
    return row.get("Focus", "").split("\n")[0]



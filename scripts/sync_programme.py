def faculty_exports(path):
    """The faculty workbook as markdown: Overview plain, Sessions per session, references as a table."""
    wb = openpyxl.load_workbook(path, data_only=True)
    files = {}
    for ws in wb.worksheets:
        name = ec.file_name(ws.title)
        if ws.title == "Reference library":
            hr = next(r for r in range(1, ws.max_row + 1) if ec.clean(ws.cell(row=r, column=1).value) == "Ref")
            headers = [h for h in ec.headers_of(ws, hr) if h]
            rows = [[ws.cell(row=r, column=c).value for c in range(1, len(headers) + 1)]
                    for r in range(hr + 1, ws.max_row + 1) if ws.cell(row=r, column=1).value]
            lines = ["# " + ws.title, ""] + [ec.clean(ws.cell(row=r, column=1).value)
                                             for r in range(1, hr) if ws.cell(row=r, column=1).value]
            lines += [""] + ec.md_table(headers, rows) + [""]
            files[name] = "\n".join(lines)
        else:
            files[name] = "\n".join(ec.export_plain(ws)[0])
    return files


def redact_faculty_exports(files, sessions, facts):
    if facts["faculty"].get("publish_names"):
        return files
    names = {s["faculty"] for s in sessions if s["faculty"].lower() not in NO_NAME}
    for n in names:
        for k in files:
            files[k] = files[k].replace(n, "[named in the workbook, not published]")
    return files



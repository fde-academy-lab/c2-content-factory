def build(report):
    facts = load_facts()
    generated = {}

    files, summary = ec.export_all(TRACKER)
    for name, text in files.items():
        generated[ec.OUT / name] = text
    wb = openpyxl.load_workbook(TRACKER, data_only=True)
    days, weeks = read_tracker_days(wb, facts, report)
    capstone = read_capstone(wb, facts)
    plan = read_plan(wb)
    sessions, overview, _ = read_faculty(FACULTY, facts, report)
    for k, want in (("Session length (minutes)", facts["faculty"]["session_minutes"]),
                    ("Faculty hours committed", facts["faculty"]["hours_committed"])):
        if k in overview and overview[k] != want:
            report.warn(f"the faculty workbook's input '{k}' is {overview[k]}; facts.yaml says {want}")

    check_calendar(days, plan, capstone, facts, report)
    check_faculty(sessions, days, plan, facts, report)
    ctx = Context(facts, days, weeks, capstone, plan, sessions)

    for name, text in redact_faculty_exports(faculty_exports(FACULTY), sessions, facts).items():
        generated[pathlib.Path("docs/faculty") / name] = text
    jwb = openpyxl.load_workbook(JOURNEY, data_only=True)
    for ws in jwb.worksheets:
        generated[pathlib.Path("docs/journey") / ec.file_name(ws.title)] = "\n".join(ec.export_plain(ws)[0])

    def sat_date(week):
        d = ctx.day.get(f"{week}/SAT")
        return d["date"] if d else None

    papers, notes = bsp.render_all(TRACKER, date_of=sat_date, existing_only=True)
    for path, text in papers.items():
        generated[path.relative_to(ROOT)] = text
    for paper, no, state, why in notes:
        if state == "broken":
            report.error(f"data/programme/paper_edits.yaml {paper} item {no}: {why}")
        elif state == "folded":
            report.warn(f"data/programme/paper_edits.yaml {paper} item {no}: {why}; delete the edit")

    generated[DAYS_JSON] = days_json(ctx)
    generated[PROGRAMME_DOCS / "calendar.md"] = calendar_page(ctx)
    generated[PROGRAMME_DOCS / "faculty-plan.md"] = faculty_page(ctx, report)
    generated[PROGRAMME_DOCS / "decisions.md"] = decisions_page(ctx)

    for path in marker_files():
        text = path.read_text(encoding="utf-8")
        if "<!-- sync:" not in text:
            continue
        new = render_blocks(text, ctx, path, report)
        if new != text:
            generated[path] = new
    generated.update(project_pack(ctx, generated))
    return generated, summary, ctx


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if an output is stale or a source disagrees")
    a = ap.parse_args()
    os.chdir(ROOT)

    report = Report()
    generated, summary, ctx = build(report)
    stale = [p for p, text in sorted(generated.items())
             if not p.exists() or p.read_text(encoding="utf-8") != text]
    orphans = sorted(p for p in ec.OUT.glob("*.md") if p.name not in {q.name for q in generated
                                                                    if q.parent == ec.OUT})

    print(f"      {len(ctx.days)} days and {len(ctx.capstone)} capstone weeks read; "
          f"{len(ctx.sessions)} faculty sessions, "
          f"{sum(1 for s in ctx.sessions if ctx.status_word(s) == 'confirmed')} confirmed")
    for w in report.warnings:
        print(f"WARN  {w}")
    for e in report.errors:
        print(f"FAIL  {e}")
    if orphans:
        print("WARN  exports with no tab in the workbook: " + ", ".join(p.name for p in orphans))

    if a.check:
        for p in stale:
            print(f"STALE {p}")
        if report.errors or stale:
            print(f"\n{len(report.errors)} error(s), {len(stale)} stale output(s). "
                  f"Run python3 scripts/sync_programme.py and commit what it writes.")
            sys.exit(1)
        print("      every output is current")
        return

    if report.errors:
        print(f"\n{len(report.errors)} error(s): nothing written. Fix the sources and run again.")
        sys.exit(1)
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(generated[p], encoding="utf-8")
        print(f"wrote {p}")
    print(f"      {len(stale)} file(s) updated, {len(generated) - len(stale)} already current")


if __name__ == "__main__":
    main()


OPEN = re.compile(r"<!-- sync:([a-z-]+)(?::([A-Za-z0-9/_-]+))? -->")
FENCE = re.compile(r"^(```|~~~).*?^\1[ \t]*$", re.M | re.S)


def audience_of(path):
    m = re.search(r"_(STUDENT|TRAINER|INTERNAL)\.", path.name)
    return m.group(1) if m else "INTERNAL"


def render_blocks(text, ctx, path, report):
    """Rewrite every sync block in one file. Inline blocks stay inline; block ones keep their lines."""
    out, pos = [], 0
    audience = audience_of(path)
    # A block inside a fenced code example is documentation of the syntax, never a live block.
    fences = [(f.start(), f.end()) for f in FENCE.finditer(text)]
    for m in OPEN.finditer(text):
        if m.start() < pos or any(a <= m.start() < b for a, b in fences):
            continue
        line_start = text.rfind("\n", 0, m.start()) + 1
        if text.count("`", line_start, m.start()) % 2:
            continue  # inside an inline code span, so it is an example
        name, arg = m.group(1), m.group(2) or ""
        tag = name + (":" + arg if arg else "")
        close = f"<!-- /sync:{tag} -->"
        end = text.find(close, m.end())
        if end < 0:
            report.error(f"{path}: <!-- sync:{tag} --> has no closing {close}")
            continue
        renderer = RENDERERS.get(name)
        if not renderer:
            report.error(f"{path}: unknown sync block '{name}'")
            continue
        try:
            body = renderer(ctx, arg, audience)
        except ValueError as e:
            report.error(f"{path}: sync:{tag}: {e}")
            continue
        inner = text[m.end():end]
        block = "\n" in inner or "\n" in body
        new_inner = f"\n{body}\n" if block else body
        out += [text[pos:m.end()], new_inner, close]
        pos = end + len(close)
    out.append(text[pos:])
    return "".join(out)


def marker_files():
    seen = []
    for base in SCAN:
        for p in sorted(pathlib.Path(base).rglob("*.md")):
            s = p.as_posix()
            if any(s.startswith(skip) for skip in SKIP_PARTS):
                continue
            seen.append(p)
    return seen + [pathlib.Path(f) for f in SCAN_FILES if pathlib.Path(f).exists()]


